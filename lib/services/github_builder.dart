import 'dart:convert';
import 'dart:typed_data';

import 'package:archive/archive.dart';

import '../core/errors.dart';
import 'http_transport.dart';
import 'templates.dart';

typedef LogFn = void Function(String message);

class GitHubRepo {
  const GitHubRepo(this.owner, this.name, this.branch);

  final String owner;
  final String name;
  final String branch;

  String get url => 'https://github.com/$owner/$name';
}

/// Talks to the GitHub REST API to build an APK in the cloud:
/// create a private repo, push the project as one commit, wait for the
/// workflow, then download the APK artifact.
class GitHubBuilder {
  GitHubBuilder({
    required this.token,
    required this.transport,
    LogFn? log,
    this.pollInterval = const Duration(seconds: 10),
    this.appearTimeout = const Duration(seconds: 120),
    this.runTimeout = const Duration(minutes: 30),
    Future<void> Function(Duration)? sleep,
    DateTime Function()? now,
  })  : _log = log ?? ((_) {}),
        _sleep = sleep ?? ((duration) => Future<void>.delayed(duration)),
        _now = now ?? DateTime.now;

  static const String _api = 'https://api.github.com';

  final String token;
  final HttpTransport transport;
  final Duration pollInterval;
  final Duration appearTimeout;
  final Duration runTimeout;
  final LogFn _log;
  final Future<void> Function(Duration) _sleep;
  final DateTime Function() _now;

  Map<String, String> get _headers => {
        'Authorization': 'Bearer $token',
        'Accept': 'application/vnd.github+json',
        'X-GitHub-Api-Version': '2022-11-28',
        'User-Agent': 'ai-app-factory',
      };

  Future<HttpResult> _call(
    String method,
    String path, {
    Object? body,
    String what = 'طلب GitHub',
  }) async {
    final result = await transport.send(
      method,
      Uri.parse('$_api$path'),
      headers: _headers,
      jsonBody: body,
    );
    return ensureOk(result, what);
  }

  /// Creates a private repository with an initial commit on its default branch.
  Future<GitHubRepo> createRepo(String name) async {
    final response = await _call(
      'POST',
      '/user/repos',
      body: {
        'name': name,
        'private': true,
        'auto_init': true,
        'description': 'Generated by AI App Factory',
      },
      what: 'إنشاء المستودع',
    );
    final data = response.json as Map<String, dynamic>;
    final owner = (data['owner'] as Map<String, dynamic>)['login'] as String;
    return GitHubRepo(
      owner,
      data['name'] as String,
      data['default_branch'] as String? ?? 'main',
    );
  }

  /// Replaces the repository content with [files] in a single commit and
  /// returns the new commit sha.
  Future<String> pushFiles(
    GitHubRepo repo,
    Map<String, String> files,
    String message,
  ) async {
    final base = '/repos/${repo.owner}/${repo.name}';
    final headSha = await _headSha(repo);

    final entries = <Map<String, String>>[];
    final paths = files.keys.toList()..sort();
    for (final path in paths) {
      final blob = await _call(
        'POST',
        '$base/git/blobs',
        body: {
          'content': base64Encode(utf8.encode(files[path]!)),
          'encoding': 'base64',
        },
        what: 'رفع الملف $path',
      );
      entries.add({
        'path': path,
        'mode': '100644',
        'type': 'blob',
        'sha': (blob.json as Map<String, dynamic>)['sha'] as String,
      });
    }

    final tree = await _call(
      'POST',
      '$base/git/trees',
      body: {'tree': entries},
      what: 'إنشاء شجرة الملفات',
    );
    final commit = await _call(
      'POST',
      '$base/git/commits',
      body: {
        'message': message,
        'tree': (tree.json as Map<String, dynamic>)['sha'],
        'parents': [headSha],
      },
      what: 'إنشاء الـ commit',
    );
    final commitSha = (commit.json as Map<String, dynamic>)['sha'] as String;

    await _call(
      'PATCH',
      '$base/git/refs/heads/${repo.branch}',
      body: {'sha': commitSha, 'force': false},
      what: 'تحديث الفرع',
    );
    return commitSha;
  }

  Future<String> _headSha(GitHubRepo repo) async {
    final path =
        '/repos/${repo.owner}/${repo.name}/git/ref/heads/${repo.branch}';
    // A brand-new repository can take a moment before its branch is readable.
    for (var attempt = 0; attempt < 6; attempt++) {
      final result = await transport.send(
        'GET',
        Uri.parse('$_api$path'),
        headers: _headers,
      );
      if (result.ok) {
        final data = result.json as Map<String, dynamic>;
        return (data['object'] as Map<String, dynamic>)['sha'] as String;
      }
      if (result.status != 404 && result.status != 409) {
        ensureOk(result, 'قراءة الفرع');
      }
      await _sleep(const Duration(seconds: 2));
    }
    throw FactoryException('تعذّر قراءة فرع المستودع الجديد.');
  }

  /// Waits for the workflow run of [headSha] and returns the finished run.
  /// If no run starts by itself, the workflow is dispatched manually.
  Future<Map<String, dynamic>> waitForRun(
    GitHubRepo repo,
    String headSha,
  ) async {
    final base = '/repos/${repo.owner}/${repo.name}/actions';
    final startedAt = _now();
    var dispatched = false;
    String? lastStatus;

    while (true) {
      final response = await _call(
        'GET',
        '$base/runs?head_sha=$headSha&per_page=5',
        what: 'قراءة حالة البناء',
      );
      final runs = ((response.json as Map<String, dynamic>)['workflow_runs']
              as List<dynamic>?) ??
          const [];
      final elapsed = _now().difference(startedAt);

      if (runs.isNotEmpty) {
        final run = runs.first as Map<String, dynamic>;
        final status = run['status'] as String? ?? 'unknown';
        if (status != lastStatus) {
          _log('حالة البناء على GitHub: $status');
          lastStatus = status;
        }
        if (status == 'completed') return run;
      } else if (!dispatched && elapsed > appearTimeout) {
        _log('لم يبدأ البناء تلقائياً، سأشغّله يدوياً...');
        await _call(
          'POST',
          '$base/workflows/$workflowFileName/dispatches',
          body: {'ref': repo.branch},
          what: 'تشغيل الـ workflow',
        );
        dispatched = true;
      }

      if (elapsed > runTimeout) {
        throw FactoryException('انتهت مهلة انتظار البناء على GitHub.');
      }
      await _sleep(pollInterval);
    }
  }

  /// Downloads the APK from the artifacts of [runId].
  Future<Uint8List> downloadApk(GitHubRepo repo, int runId) async {
    final base = '/repos/${repo.owner}/${repo.name}/actions';
    final listing = await _call(
      'GET',
      '$base/runs/$runId/artifacts',
      what: 'قراءة ملفات البناء',
    );
    final artifacts = ((listing.json as Map<String, dynamic>)['artifacts']
            as List<dynamic>?) ??
        const [];
    final usable = artifacts
        .whereType<Map<String, dynamic>>()
        .where((artifact) => artifact['expired'] != true)
        .toList();
    if (usable.isEmpty) {
      throw FactoryException('لم يُنتج البناء أي ملف APK.');
    }

    final id = usable.first['id'];
    final bytes = await _fetchRedirected('$base/artifacts/$id/zip');
    final archive = ZipDecoder().decodeBytes(bytes);
    for (final file in archive.files) {
      if (file.isFile && file.name.toLowerCase().endsWith('.apk')) {
        return Uint8List.fromList(file.content as List<int>);
      }
    }
    throw FactoryException('الأرشيف المحمَّل لا يحتوي على ملف APK.');
  }

  /// Returns the last part of the failed job log, for the AI to fix.
  Future<String> failureLog(GitHubRepo repo, int runId) async {
    final base = '/repos/${repo.owner}/${repo.name}/actions';
    final jobs = await _call(
      'GET',
      '$base/runs/$runId/jobs',
      what: 'قراءة مهام البناء',
    );
    final list =
        ((jobs.json as Map<String, dynamic>)['jobs'] as List<dynamic>?) ??
            const [];
    for (final job in list.whereType<Map<String, dynamic>>()) {
      if (job['conclusion'] != 'failure') continue;
      final bytes = await _fetchRedirected('$base/jobs/${job['id']}/logs');
      final text = utf8.decode(bytes, allowMalformed: true);
      const limit = 6000;
      return text.length > limit ? text.substring(text.length - limit) : text;
    }
    return 'No failed job log was available.';
  }

  /// GitHub answers artifact and log downloads with a redirect to a signed
  /// URL. The signed URL is fetched WITHOUT the token so it is never leaked.
  Future<Uint8List> _fetchRedirected(String path) async {
    final first = await transport.send(
      'GET',
      Uri.parse('$_api$path'),
      headers: _headers,
      followRedirects: false,
    );
    if (first.isRedirect) {
      final location = first.header('location');
      if (location == null || location.isEmpty) {
        throw FactoryException('رد GitHub بلا عنوان تحميل.');
      }
      final second = await transport.send('GET', Uri.parse(location));
      return ensureOk(second, 'تحميل الملف').bodyBytes;
    }
    return ensureOk(first, 'تحميل الملف').bodyBytes;
  }
}
